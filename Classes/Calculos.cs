using System;
using System.Collections.Generic;
using System.Text;

namespace Classes
{
    public class Calculos
    {
        // metodo public / private
        public int Somar(int a, int b)
        {
            int resultado = a + b;
            return resultado;
        }

        public int Subtrair(int a, int b)
        {
            return a - b;
        }
    }
}
